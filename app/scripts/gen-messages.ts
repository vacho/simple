// Generates src/lib/i18n/keys.ts from messages/en.json: every message key with the parameters
// its English text takes (undefined when it takes none), so t() with an unknown key or a missing
// parameter fails to compile (D14).
// Run by predev, prebuild and npm run check.
import { parse, TYPE, type MessageFormatElement } from '@formatjs/icu-messageformat-parser';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'messages/en.json');
const target = path.join(root, 'src/lib/i18n/keys.ts');

type EnglishCatalog = Record<string, { text: string; description: string }>;

// TypeScript type of the value each kind of ICU argument accepts.
const argumentType: Partial<Record<TYPE, string>> = {
	[TYPE.argument]: 'string | number',
	[TYPE.number]: 'number',
	[TYPE.plural]: 'number',
	[TYPE.date]: 'Date | number',
	[TYPE.time]: 'Date | number',
	[TYPE.select]: 'string',
	[TYPE.tag]: '(chunks: string[]) => string'
};

function collect(elements: MessageFormatElement[], params: Map<string, string>): void {
	for (const element of elements) {
		const type = argumentType[element.type];
		if (type && 'value' in element) params.set(element.value, type);
		if ('options' in element) {
			for (const option of Object.values(element.options)) collect(option.value, params);
		}
		if (element.type === TYPE.tag) collect(element.children, params);
	}
}

function paramsType(text: string): string {
	const params = new Map<string, string>();
	collect(parse(text), params);
	if (params.size === 0) return 'undefined';
	const fields = [...params].map(([name, type]) => `${JSON.stringify(name)}: ${type}`);
	return `{ ${fields.join('; ')} }`;
}

const catalog = JSON.parse(readFileSync(source, 'utf8')) as EnglishCatalog;
const entries = Object.entries(catalog).map(
	([key, { text }]) => `\t${JSON.stringify(key)}: ${paramsType(text)};`
);

const output = `// Generated by scripts/gen-messages.ts from messages/en.json. Do not edit.
export interface MessageParams {
${entries.join('\n')}
}

export type MessageKey = keyof MessageParams;
`;

writeFileSync(target, output);
