// Generates src/lib/i18n/keys.ts from messages/en.json: every message key with the parameters
// its English text takes (undefined when it takes none), so t() with an unknown key or a missing
// parameter fails to compile (D14). Run by predev, prebuild and npm run check.
import { TYPE } from '@formatjs/icu-messageformat-parser';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { appRoot, argumentsOf, messagesDir, readCatalog, type EnglishEntry } from './messages.ts';

const target = path.join(appRoot, 'src/lib/i18n/keys.ts');

// TypeScript type of the value each kind of ICU argument accepts.
const argumentType: Partial<Record<TYPE, string>> = {
	[TYPE.argument]: 'string | number',
	[TYPE.number]: 'number',
	[TYPE.plural]: 'number',
	[TYPE.date]: 'Date | number',
	[TYPE.time]: 'Date | number',
	[TYPE.select]: 'string',
	[TYPE.tag]: '(chunks: string[]) => string'
};

function paramsType(text: string): string {
	const params = [...argumentsOf(text)];
	if (params.length === 0) return 'undefined';
	const fields = params.map(([name, type]) => `${JSON.stringify(name)}: ${argumentType[type]}`);
	return `{ ${fields.join('; ')} }`;
}

const catalog = readCatalog<EnglishEntry>(messagesDir, 'en');
const entries = Object.entries(catalog).map(
	([key, { text }]) => `\t${JSON.stringify(key)}: ${paramsType(text)};`
);

writeFileSync(
	target,
	`// Generated by scripts/gen-messages.ts from messages/en.json. Do not edit.
export interface MessageParams {
${entries.join('\n')}
}

export type MessageKey = keyof MessageParams;
`
);
